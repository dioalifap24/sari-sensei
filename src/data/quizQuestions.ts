// Shuffle helper for quiz options to ensure the correct answer is randomized across A, B, C, D
export const shuffleQuestionOptions = (question: QuizQuestion): { options: string[]; correctIndex: number } => {
  const originalOptions = [...question.options];
  const correctText = originalOptions[question.correctAnswerIndex];
  
  // True Fisher-Yates shuffle
  const shuffled = [...originalOptions];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  
  const newCorrectIndex = shuffled.indexOf(correctText);
  return {
    options: shuffled,
    correctIndex: newCorrectIndex,
  };
};
